import { expect, test } from '@playwright/test'

test('showcase displays the initial game in a full-width stage', async ({ page }) => {
  await page.goto('/')
  const showcase = page.getByRole('region', { name: '[ Game Dev ]' })
  await expect(showcase.getByRole('heading', { name: '[ Game Dev ]' })).toBeVisible()
  await expect(showcase.getByRole('heading', { name: 'KonTEXTo' })).toBeVisible()
  await expect(showcase.getByText(/An immersive campus life simulator/)).toBeVisible()
  await expect(showcase.locator('canvas')).toBeAttached()
  await expect(showcase.locator('[data-tv-state]')).toHaveAttribute('data-tv-state', 'ready', { timeout: 20000 })
  const dimensions = await page.evaluate(() => ({ width: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }))
  expect(dimensions.scroll).toBeLessThanOrEqual(dimensions.width)
  const canvas = await showcase.locator('canvas').boundingBox()
  expect(canvas).not.toBeNull()
  expect(Math.abs(canvas!.width - dimensions.width)).toBeLessThan(2)
  const title = await showcase.getByRole('heading', { name: 'KonTEXTo' }).boundingBox()
  const description = await showcase.getByText(/An immersive campus life simulator/).boundingBox()
  const previous = await showcase.getByRole('button', { name: 'Previous' }).boundingBox()
  const next = await showcase.getByRole('button', { name: 'Next', exact: true }).boundingBox()
  expect(title!.y + title!.height).toBeLessThanOrEqual(canvas!.y + 2)
  expect(description!.y).toBeGreaterThanOrEqual(canvas!.y + canvas!.height - 2)
  expect(previous!.x).toBeLessThan(next!.x)
  expect(Math.abs(previous!.y + previous!.height / 2 - (canvas!.y + canvas!.height / 2))).toBeLessThan(3)
  expect(Math.abs(next!.y + next!.height / 2 - (canvas!.y + canvas!.height / 2))).toBeLessThan(3)
})

test('model failure shows fallback while game details remain accessible', async ({ page }) => {
  await page.route('**/practice_tv.gltf*', route => route.request().resourceType() === 'script' ? route.continue() : route.abort())
  await page.goto('/')
  const showcase = page.getByRole('region', { name: '[ Game Dev ]' })
  await expect(showcase.locator('[data-tv-state]')).toHaveAttribute('data-tv-state', 'unavailable')
  await expect(showcase.getByRole('status').filter({ hasText: 'TV image unavailable' })).toBeVisible()
  await expect(showcase.getByRole('heading', { name: 'KonTEXTo' })).toBeVisible()
  await expect(showcase.getByRole('link', { name: /Play/ })).toHaveAttribute('href', 'https://kirubiisfyne.itch.io/kontexto')
})
