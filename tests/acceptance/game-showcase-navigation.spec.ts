import { expect, test } from '@playwright/test'
import { navigateGame, showcaseUrl } from './game-showcase-fixtures'

test('navigation wraps and Play follows selected game', async ({ page, context }) => {
  await page.goto(showcaseUrl())
  const viewer = page.getByRole('application', { name: 'Game navigation' })
  const play = page.getByRole('link', { name: /Play/ })
  await expect(play).toHaveAttribute('href', 'https://kirubiisfyne.itch.io/kontexto')
  await page.keyboard.press('Tab')
  await expect(viewer).toBeFocused()
  await expect(page.getByText('[ D-pad / focus + arrows: change game ]')).toBeVisible()
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('Tab')
  await expect(play).toBeFocused()
  expect(await play.evaluate((element) => element.matches(':focus-visible') && getComputedStyle(element).outlineStyle !== 'none')).toBe(true)
  await expect(page.getByRole('heading', { name: 'Anii! Grow to Know' })).toBeVisible()
  await expect(play).toHaveAttribute('href', 'https://kirubiisfyne.itch.io/anii-grow-to-know')
  await expect(play).toHaveAttribute('target', '_blank')
  await expect(play).toHaveAttribute('rel', /noopener/)
  await expect(page.locator('[aria-live="polite"]').filter({ hasText: 'Anii! Grow to Know' })).toHaveText('Anii! Grow to Know, 2 of 2')
  await navigateGame(page, 'next')
  await expect(page.getByRole('heading', { name: 'KonTEXTo' })).toBeVisible()
  await navigateGame(page, 'previous')
  await expect(page.getByRole('heading', { name: 'Anii! Grow to Know' })).toBeVisible()
  await context.route('https://kirubiisfyne.itch.io/**', route => route.fulfill({ body: 'itch' }))
  const popup = page.waitForEvent('popup')
  await play.click()
  const opened = await popup
  await opened.waitForLoadState()
  expect(opened.url()).toBe('https://kirubiisfyne.itch.io/anii-grow-to-know')
})

test('empty and single catalogs have safe controls', async ({ page }) => {
  await page.goto(showcaseUrl('empty'))
  await expect(page.getByText('No games available yet.')).toBeVisible()
  await expect(page.getByRole('link', { name: /Play/ })).toHaveCount(0)
  await page.goto(showcaseUrl('single'))
  await expect(page.getByRole('application', { name: 'Game navigation' })).toHaveAttribute('aria-disabled', 'true')
  await navigateGame(page, 'next')
  await expect(page.getByRole('heading', { name: 'KonTEXTo' })).toBeVisible()
  await expect(page.getByRole('link', { name: /Play/ })).toBeVisible()
})
