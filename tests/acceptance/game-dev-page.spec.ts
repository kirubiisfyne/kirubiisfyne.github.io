import { expect, test } from '@playwright/test'

test('Game Dev presents featured game, screenshots, technical breakdowns and other games', async ({ page }) => {
  await page.goto('http://127.0.0.1:5489/game-dev/')
  await expect(page.getByRole('heading', { name: '[ Game Dev ]' })).toBeVisible()
  await expect(page.getByText('Unity / Godot / UE5')).toBeVisible()
  await expect(page.getByText('C# / Python / GDScript')).toBeVisible()
  await expect(page.getByTitle('Anii! Grow to Know trailer')).toHaveAttribute('src', /youtube-nocookie\.com\/embed\/xJZeUs_QqVA/)
  const thumbnail = page.getByRole('button', { name: 'View Anii screenshot 1 of 5' })
  await expect(page.locator('.anii-thumbnails button')).toHaveCount(5)
  await thumbnail.click()
  const dialog = page.getByRole('dialog', { name: 'Anii screenshot viewer' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByText('Screenshot 1 / 5')).toBeVisible()
  await page.keyboard.press('ArrowRight')
  await expect(dialog.getByText('Screenshot 2 / 5')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(thumbnail).toBeFocused()
  await expect(page.getByRole('heading', { name: '[ Technical Breakdowns ]' })).toBeVisible()
  await expect(page.getByRole('heading', { name: '[ Other Games ]' })).toBeVisible()
  await expect(page.getByRole('link', { name: /KonTEXTo.*View on itch.io/ })).toHaveAttribute('href', 'https://kirubiisfyne.itch.io/kontexto')
  await expect(page.getByRole('link', { name: /Purgatoryo.*View on itch.io/ })).toHaveAttribute('href', 'https://kirubiisfyne.itch.io/purgatoryo')
})
